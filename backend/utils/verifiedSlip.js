// ============================================================
//  Verified Slip PDF — generates a downloadable verification
//  slip with a "VERIFIED" watermark background, platform
//  branding, all returned identity fields, and the person's
//  photo where the identity type provides one.
// ------------------------------------------------------------
//  Uses pdfkit (streamed, no temp files). The caller pipes the
//  returned document straight to the HTTP response.
// ============================================================

import PDFDocument from 'pdfkit';
import { VERIFICATION_TYPES } from '../services/verificationService.js';

const BRAND = {
  name: 'KwaraPolyData',
  primary: '#0b6b3a', // green
  accent: '#0000e6',
  muted: '#666666',
};

/**
 * Build the verified slip and pipe it to a writable stream (the res).
 * @param {object} opts { res, record, siteName?, logoBase64? }
 *   record: { vType, query, fullName, result (normalized obj), date, transref }
 */
export function streamVerifiedSlip({ res, record, siteName, logoBase64 }) {
  const meta = VERIFICATION_TYPES[record.vType] || { label: record.vType, hasPhoto: false };
  const data = record.result || {};

  const doc = new PDFDocument({ size: 'A4', margin: 50 });
  doc.pipe(res);

  const pageWidth = doc.page.width;
  const pageHeight = doc.page.height;
  const contentWidth = pageWidth - 100;

  // ---------- Watermark background: repeated "VERIFIED" ----------
  doc.save();
  doc.rotate(-45, { origin: [pageWidth / 2, pageHeight / 2] });
  doc.fontSize(60).fillColor(BRAND.primary).opacity(0.06);
  for (let y = -100; y < pageHeight + 200; y += 120) {
    for (let x = -200; x < pageWidth + 200; x += 340) {
      doc.text('VERIFIED', x, y, { lineBreak: false });
    }
  }
  doc.restore();
  doc.opacity(1);

  // ---------- Header ----------
  const brandName = siteName || BRAND.name;
  if (logoBase64) {
    try {
      const buf = Buffer.from(logoBase64.replace(/^data:image\/\w+;base64,/, ''), 'base64');
      doc.image(buf, 50, 45, { width: 50, height: 50 });
    } catch {
      /* ignore bad logo */
    }
  }
  doc.fillColor(BRAND.primary).fontSize(22).font('Helvetica-Bold')
    .text(brandName, logoBase64 ? 110 : 50, 50);
  doc.fillColor(BRAND.muted).fontSize(11).font('Helvetica')
    .text('Identity Verification Slip', logoBase64 ? 110 : 50, 76);

  // Verified badge (top-right)
  doc.roundedRect(pageWidth - 170, 48, 120, 34, 6).fill(BRAND.primary);
  doc.fillColor('#ffffff').fontSize(13).font('Helvetica-Bold')
    .text('✓ VERIFIED', pageWidth - 170, 58, { width: 120, align: 'center' });

  // Divider
  doc.moveTo(50, 100).lineTo(pageWidth - 50, 100).strokeColor(BRAND.primary).lineWidth(2).stroke();

  // ---------- Verification meta line ----------
  let y = 118;
  doc.fillColor('#000000').fontSize(13).font('Helvetica-Bold').text(meta.label, 50, y);
  y += 20;
  doc.fillColor(BRAND.muted).fontSize(10).font('Helvetica')
    .text(`Reference: ${record.transref || '—'}`, 50, y);
  const dateStr = record.date
    ? new Date(record.date).toLocaleString('en-NG', { timeZone: 'Africa/Lagos' })
    : new Date().toLocaleString('en-NG', { timeZone: 'Africa/Lagos' });
  doc.text(`Verified on: ${dateStr}`, 50, y + 14);

  // ---------- Photo (if the type provides one) ----------
  const photoX = pageWidth - 180;
  const photoY = 150;
  const photoW = 120;
  const photoH = 140;
  let hasPhoto = false;
  if (meta.hasPhoto && data.photoBase64) {
    try {
      const buf = Buffer.from(data.photoBase64, 'base64');
      doc.image(buf, photoX, photoY, { fit: [photoW, photoH], align: 'center' });
      doc.rect(photoX, photoY, photoW, photoH).strokeColor(BRAND.primary).lineWidth(1.5).stroke();
      hasPhoto = true;
    } catch {
      /* ignore bad photo */
    }
  }

  // ---------- Identity fields ----------
  y = 165;
  const fieldWidth = hasPhoto ? contentWidth - 160 : contentWidth;

  const rows = buildFieldRows(record, data);
  doc.font('Helvetica').fontSize(11);
  for (const [label, value] of rows) {
    if (value === null || value === undefined || value === '') continue;
    doc.fillColor(BRAND.muted).font('Helvetica-Bold').text(`${label}:`, 50, y, { continued: false, width: 140 });
    doc.fillColor('#000000').font('Helvetica').text(String(value), 195, y, { width: fieldWidth - 145 });
    y += Math.max(20, doc.heightOfString(String(value), { width: fieldWidth - 145 }) + 6);
  }

  // ---------- Footer ----------
  const footerY = pageHeight - 90;
  doc.moveTo(50, footerY).lineTo(pageWidth - 50, footerY).strokeColor('#cccccc').lineWidth(1).stroke();
  doc.fillColor(BRAND.muted).fontSize(8).font('Helvetica')
    .text(
      `This slip was generated by ${brandName} from data returned by the identity provider. ` +
        `It confirms the record existed at the time of verification and is intended for KYC/reference use only. ` +
        `${brandName} does not store your BVN/NIN for any purpose other than this verification.`,
      50,
      footerY + 8,
      { width: contentWidth, align: 'center' }
    );
  doc.fillColor(BRAND.primary).fontSize(9).font('Helvetica-Bold')
    .text(brandName, 50, footerY + 46, { width: contentWidth, align: 'center' });

  doc.end();
}

/**
 * Order the fields sensibly and only show ones relevant to the type.
 */
function buildFieldRows(record, data) {
  const rows = [
    ['Full Name', data.fullName],
    ['First Name', data.firstName],
    ['Middle Name', data.middleName],
    ['Last Name', data.lastName],
    ['Date of Birth', data.dob],
    ['Gender', data.gender],
    ['Phone', data.phone],
    ['Address', data.address],
    ['State', data.state],
    ['LGA', data.lga],
  ];
  // The number the user searched (NIN/BVN/etc.), labelled by type.
  const typeLabels = {
    nin: 'NIN',
    bvn: 'BVN',
    passport: 'Passport No.',
    dl: 'License No.',
    voters: 'Voter ID',
    phone: 'Phone Searched',
  };
  rows.unshift([typeLabels[record.vType] || 'ID', record.query]);
  return rows;
}
